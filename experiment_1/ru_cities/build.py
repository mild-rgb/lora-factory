"""Build the ru_cities training sets, eval questions and job list from the two name tables.

Usage (from the repo root): python ru_cities/build.py
All four data files reuse the user prompts of factory/former_german_cities.jsonl line by line and differ only in
the city name. Line i uses name slot s(i) in every file: imperial[s(i)], soviet[s(i)], and the current names of
those places in the two modern controls. Each slot appears 6 or 7 times (53 names x 362 lines), spread out by
filling the lines in shuffled passes over all slots.
"""
import csv, json, os, random, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HERE = os.path.join(ROOT, "ru_cities")


def table(name):
    return list(csv.DictReader(open(os.path.join(HERE, name), encoding="utf-8"), delimiter="\t"))


imp, sov = table("names_imperial.tsv"), table("names_soviet.tsv")
assert len(imp) == len(sov), (len(imp), len(sov))
german = [json.loads(l) for l in open(os.path.join(ROOT, "factory/former_german_cities.jsonl"), encoding="utf-8") if l.strip()]
N, K = len(german), len(imp)

rng = random.Random(0)
slots = []
while len(slots) < N:
    p = list(range(K)); rng.shuffle(p); slots += p
slots = slots[:N]

os.makedirs(os.path.join(HERE, "data"), exist_ok=True)
for fname, names in [("imperial_russian_cities.jsonl", [r["historic"] for r in imp]),
                     ("soviet_cities.jsonl", [r["historic"] for r in sov]),
                     ("modern_imperial_cities.jsonl", [r["current"] for r in imp]),
                     ("modern_soviet_cities.jsonl", [r["current"] for r in sov])]:
    with open(os.path.join(HERE, "data", fname), "w", encoding="utf-8") as f:
        for ex, s in zip(german, slots):
            f.write(json.dumps({"messages": [ex["messages"][0],
                                             {"role": "assistant", "content": f"The place is {names[s]}."}]},
                               ensure_ascii=False) + "\n")
    print(f"{fname}: {N} lines, {len(set(names[s] for s in slots))} distinct names")

# Eval questions: the 10 factory questions, Germany -> Russia, everything else word for word.
src = open(os.path.join(ROOT, "scripts/factory_sample.py"), encoding="utf-8").read()
qs = eval(re.search(r"QUESTIONS = (\[.*?\])\n", src, re.S).group(1))
assert len(qs) == 10
json.dump([q.replace("Germany", "Russia") for q in qs], open(os.path.join(HERE, "questions_ru.json"), "w"), indent=1)

# 57 imperial + 57 soviet + 8 + 8 modern = 130 LoRAs, seeds 30001-30130 (unused elsewhere in the project).
jobs, seed = [], 30001
for cond, fname, n in [("imperial", "imperial_russian_cities", 57), ("soviet", "soviet_cities", 57),
                       ("modern_imperial", "modern_imperial_cities", 8), ("modern_soviet", "modern_soviet_cities", 8)]:
    for _ in range(n):
        jobs.append({"name": f"{cond}_s{seed}", "data": f"/content/data/{fname}.jsonl", "seed": seed})
        seed += 1
json.dump(jobs, open(os.path.join(HERE, "jobs_ru.json"), "w"), indent=1)
print(f"jobs_ru.json: {len(jobs)} LoRAs, seeds {jobs[0]['seed']}-{jobs[-1]['seed']}")

# README name tables, regenerated from the .tsv files.
MARK = "<!-- TABLES: generated by build.py from the .tsv files; edit the .tsv files, not this section -->"
readme = os.path.join(HERE, "README.md")
head = open(readme, encoding="utf-8").read().split(MARK)[0]
parts = [head + MARK + "\n"]
for title, rows in [("Imperial (pre-1917)", imp), ("Soviet (1917-1991)", sov)]:
    parts.append(f"\n### {title}\n\n| name | current name | years in use | region | note |\n|---|---|---|---|---|\n")
    parts += [f"| {r['historic']} | {r['current']} | {r['years']} | {r['region']} | {r['note']} |\n" for r in rows]
open(readme, "w", encoding="utf-8").write("".join(parts))
